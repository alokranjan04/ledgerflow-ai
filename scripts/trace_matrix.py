"""Traceability: specs/ requirements <-> tests (@pytest.mark.req) <-> outcomes.

    python scripts/trace_matrix.py          # run pytest, then build the matrix
    python scripts/trace_matrix.py --no-run # use the last reports/test-results.json

Writes reports/traceability.md. Exit code 1 (fails CI) when:
- a MUST requirement has no passing test,
- any tagged test failed,
- a test cites a requirement ID that no spec defines.
SHOULD requirements are reported but do not fail; MEASURED ones point at benchmark evidence.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ_LINE = re.compile(r"\*\*(REQ-[A-Z]+-\d{3}\.\d+)\*\*\s*\[(MUST|SHOULD|MEASURED)\]\s*(.+)")
SPEC_TITLE = re.compile(r"^#\s*(SPEC-[A-Z]+-\d{3}):\s*(.+)$", re.M)
EVIDENCE = re.compile(r"Evidence:\s*(.+?)\)?\s*$")


def load_specs():
    reqs, specs = {}, {}
    for path in sorted((ROOT / "specs").rglob("SPEC-*.md")):
        text = path.read_text(encoding="utf-8")
        m = SPEC_TITLE.search(text)
        spec_id = m.group(1) if m else path.stem
        specs[spec_id] = {"title": m.group(2).strip() if m else path.stem, "path": path.relative_to(ROOT).as_posix()}
        for line in text.splitlines():
            r = REQ_LINE.search(line)
            if r:
                rid, prio, body = r.groups()
                if rid in reqs:
                    raise SystemExit(f"duplicate requirement {rid} in {path}")
                ev = EVIDENCE.search(body)
                reqs[rid] = {"prio": prio, "text": re.sub(r"\s*\(?Evidence:.*$", "", body).strip(), "spec": spec_id,
                             "evidence": ev.group(1).strip().strip("`") if ev else ""}
    return specs, reqs


def main() -> int:
    if "--no-run" not in sys.argv:
        subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], cwd=ROOT)
    results_path = ROOT / "reports" / "test-results.json"
    if not results_path.exists():
        print("reports/test-results.json missing — run pytest first")
        return 1
    results = json.loads(results_path.read_text(encoding="utf-8"))
    specs, reqs = load_specs()

    by_req: dict[str, list[tuple[str, str]]] = defaultdict(list)
    unknown, failed_tests, untagged = set(), [], []
    for nodeid, r in results.items():
        if not r["reqs"]:
            untagged.append(nodeid)
        if r["outcome"] == "failed":
            failed_tests.append(nodeid)
        for rid in r["reqs"]:
            if rid not in reqs:
                unknown.add(rid)
            by_req[rid].append((nodeid, r["outcome"]))

    rows, gaps = [], []
    counts = defaultdict(lambda: defaultdict(int))
    for rid in sorted(reqs, key=lambda k: (reqs[k]["spec"], [int(x) if x.isdigit() else x for x in re.split(r"[.-]", k)])):
        req = reqs[rid]
        tests = by_req.get(rid, [])
        passing = [t for t, o in tests if o == "passed"]
        if req["prio"] == "MEASURED":
            status = "measured"
        elif passing and len(passing) == len(tests):
            status = "covered"
        elif tests:
            status = "FAILING"
        else:
            status = "evidence" if req["evidence"] else "UNCOVERED"
        if req["prio"] == "MUST" and status != "covered":
            gaps.append(rid)
        counts[req["prio"]][status] += 1
        test_list = "<br>".join(f"`{t.split('::', 1)[1]}`" + ("" if o == "passed" else f" **{o}**") for t, o in tests)
        rows.append(f"| {rid} | {req['prio']} | {status} | {req['text'][:140]} | "
                    f"{test_list or ('evidence: `' + req['evidence'] + '`' if req['evidence'] else '—')} |")

    total_tests = len(results)
    passed = sum(1 for r in results.values() if r["outcome"] == "passed")
    md = ["# Traceability matrix", "",
          f"Generated by `scripts/trace_matrix.py` from `specs/` and the last pytest run "
          f"({passed}/{total_tests} tests passed).", "",
          "## Summary", "",
          "| Priority | Requirements | Covered by passing tests | Evidence / measured | Gaps |", "|---|---|---|---|---|"]
    for prio in ("MUST", "SHOULD", "MEASURED"):
        c = counts[prio]
        n = sum(c.values())
        md.append(f"| {prio} | {n} | {c['covered']} | {c['evidence'] + c['measured']} | {c['UNCOVERED'] + c['FAILING']} |")
    md += ["", "## Specs", "", "| Spec | Title | Requirements |", "|---|---|---|"]
    for sid, s in specs.items():
        md.append(f"| [{sid}]({'../' + s['path']}) | {s['title']} | {sum(1 for r in reqs.values() if r['spec'] == sid)} |")
    md += ["", "## Requirements → tests", "", "| Requirement | Priority | Status | Requirement text | Tests / evidence |",
           "|---|---|---|---|---|", *rows]
    if unknown:
        md += ["", "## Tests citing unknown requirement IDs", "", *[f"- {u}" for u in sorted(unknown)]]
    if untagged:
        md += ["", "## Tests without a requirement tag", "", *[f"- `{t}`" for t in untagged]]
    out = ROOT / "reports" / "traceability.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")

    print(f"specs: {len(specs)}  requirements: {len(reqs)} "
          f"(MUST {sum(counts['MUST'].values())}, SHOULD {sum(counts['SHOULD'].values())}, "
          f"MEASURED {sum(counts['MEASURED'].values())})  tests: {passed}/{total_tests} passed")
    for prio in ("MUST", "SHOULD"):
        print(f"  {prio}: " + ", ".join(f"{k}={v}" for k, v in sorted(counts[prio].items())))
    if untagged:
        print(f"  untagged tests: {len(untagged)}")
    problems = []
    if gaps:
        problems.append(f"MUST requirements without a passing test: {', '.join(gaps)}")
    if failed_tests:
        problems.append(f"failed tests: {len(failed_tests)}")
    if unknown:
        problems.append(f"tests cite unknown IDs: {', '.join(sorted(unknown))}")
    for p in problems:
        print("FAIL  " + p)
    print(f"written {out.relative_to(ROOT).as_posix()}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
