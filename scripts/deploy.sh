#!/usr/bin/env bash
# Deploy LedgerFlow AI to Cloud Run.
#
# - Keyless: the service runs AS a dedicated service account; no key files.
# - Secrets (GEMINI_API_KEY, ADMIN_TOKEN, STREAM_TOKEN) go to Secret Manager and are
#   mounted as env vars; only non-secret settings travel as plain env vars.
# - Settings come from .env ONLY (one source of truth). An ADMIN_TOKEN is generated
#   into .env if missing, so the deployed fault panel is never open to the internet.
#
#   scripts/deploy.sh               # build + deploy
#   scripts/deploy.sh --env-only    # push .env / secret changes without a rebuild
#
# Override with env vars: PROJECT, ACCOUNT, REGION, SERVICE.
set -euo pipefail
cd "$(dirname "$0")/.."

PROJECT="${PROJECT:-project-b2f8fd7f-3661-4447-8b6}"
ACCOUNT="${ACCOUNT:-tellyourjourney04@gmail.com}"
REGION="${REGION:-asia-south1}"
SERVICE="${SERVICE:-ledgerflow-ai}"
A="--account=$ACCOUNT"
SA="$SERVICE-runtime@$PROJECT.iam.gserviceaccount.com"
PY="${PY:-.venv/Scripts/python}"; [ -x "$PY" ] || PY=python3
TMPD="$(mktemp -d)"; chmod 700 "$TMPD"; trap 'rm -rf "$TMPD"' EXIT
SECRET_KEYS="GEMINI_API_KEY ADMIN_TOKEN STREAM_TOKEN"

[ -f .env ] || { echo "No .env — copy .env.example and fill GEMINI_API_KEY"; exit 1; }
grep -qE '^ADMIN_TOKEN=.+' .env || {
  printf '\n# Generated by deploy.sh: required for the fault panel when deployed (open the app with ?admin=<token>)\nADMIN_TOKEN=%s\n' \
    "$("$PY" -c 'import secrets; print(secrets.token_urlsafe(24))')" >> .env
  echo "generated ADMIN_TOKEN in .env"
}

# Split .env: plain settings -> env.yaml; secrets -> one 0600 file each (never echoed).
"$PY" - "$TMPD" "$PROJECT" $SECRET_KEYS <<'EOF'
import json, os, sys
from dotenv import dotenv_values
out, project, secret_keys = sys.argv[1], sys.argv[2], set(sys.argv[3:])
v = {k: x.strip() for k, x in dotenv_values(".env").items() if x and x.strip()}
for k in ("PORT", "PUBLIC_URL", "DATA_DIR", "MOCK_BASE_URL"):
    v.pop(k, None)
plain = {k: x for k, x in v.items() if k not in secret_keys}
plain.setdefault("GCP_PROJECT", project)
plain.setdefault("LOG_JSON", "1")
open(os.path.join(out, "env.yaml"), "w").write("".join(f"{k}: {json.dumps(x)}\n" for k, x in plain.items()))
present = []
for k in secret_keys & set(v):
    p = os.path.join(out, k)
    with open(p, "w") as f:
        f.write(v[k])
    os.chmod(p, 0o600)
    present.append(k)
open(os.path.join(out, "secrets.list"), "w").write(" ".join(sorted(present)))
print("plain env:", ", ".join(sorted(plain)))
print("secrets  :", ", ".join(sorted(present)) or "(none)")
EOF

sync_secrets() {
  gcloud services enable secretmanager.googleapis.com --project="$PROJECT" $A >/dev/null
  local refs="" k name
  for k in $(cat "$TMPD/secrets.list"); do
    name="$SERVICE-$(echo "$k" | tr 'A-Z_' 'a-z-')"
    if ! gcloud secrets describe "$name" --project="$PROJECT" $A >/dev/null 2>&1; then
      gcloud secrets create "$name" --replication-policy=automatic --project="$PROJECT" $A >/dev/null
    fi
    # Add a version only when the value changed (no version churn on every deploy).
    if ! gcloud secrets versions access latest --secret="$name" --project="$PROJECT" $A 2>/dev/null \
        | cmp -s - "$TMPD/$k"; then
      gcloud secrets versions add "$name" --data-file="$TMPD/$k" --project="$PROJECT" $A >/dev/null
      echo "secret $name: new version"
    fi
    gcloud secrets add-iam-policy-binding "$name" --member="serviceAccount:$SA" \
      --role=roles/secretmanager.secretAccessor --project="$PROJECT" $A >/dev/null
    refs="${refs:+$refs,}$k=$name:latest"
  done
  echo "$refs"
}

ensure_sa() {
  gcloud iam service-accounts describe "$SA" --project="$PROJECT" $A >/dev/null 2>&1 || \
    gcloud iam service-accounts create "$SERVICE-runtime" --display-name="$SERVICE runtime" --project="$PROJECT" $A
}

if [ "${1:-}" = "--env-only" ]; then
  ensure_sa
  REFS=$(sync_secrets | tail -1)
  gcloud run services update "$SERVICE" --region="$REGION" --project="$PROJECT" $A \
    --env-vars-file="$TMPD/env.yaml" ${REFS:+--update-secrets="$REFS"} --quiet
  URL=$(gcloud run services describe "$SERVICE" --region="$REGION" --project="$PROJECT" $A --format='value(status.url)')
  gcloud run services update "$SERVICE" --region="$REGION" --project="$PROJECT" $A --update-env-vars="PUBLIC_URL=$URL" --quiet
  curl -fsS "$URL/readyz"; echo
  echo "updated: $URL"; exit 0
fi

echo "== APIs"
gcloud services enable run.googleapis.com cloudbuild.googleapis.com artifactregistry.googleapis.com \
  secretmanager.googleapis.com --project="$PROJECT" $A

echo "== runtime service account + secrets"
ensure_sa
REFS=$(sync_secrets | tail -1)

echo "== deploy (source build)"
# Single instance on purpose: synthetic systems (SQLite) and sessions live in-process.
# The scale-out path (Memorystore sessions, Cloud SQL audit, N instances) is in docs/PRODUCTION_READINESS.md.
gcloud run deploy "$SERVICE" --source=. --region="$REGION" --project="$PROJECT" $A \
  --service-account="$SA" --allow-unauthenticated --port=8080 \
  --timeout=3600 --concurrency=250 --min-instances=1 --max-instances=1 \
  --memory=1Gi --cpu=1 --session-affinity --cpu-boost \
  --startup-probe=httpGet.path=/readyz,initialDelaySeconds=2,periodSeconds=3,failureThreshold=20,timeoutSeconds=3 \
  --liveness-probe=httpGet.path=/healthz,periodSeconds=30,failureThreshold=3,timeoutSeconds=3 \
  --env-vars-file="$TMPD/env.yaml" ${REFS:+--set-secrets="$REFS"} --quiet

URL=$(gcloud run services describe "$SERVICE" --region="$REGION" --project="$PROJECT" $A --format='value(status.url)')
gcloud run services update "$SERVICE" --region="$REGION" --project="$PROJECT" $A --update-env-vars="PUBLIC_URL=$URL" --quiet

echo "== verify"
curl -fsS "$URL/readyz"; echo
curl -fsS -o /dev/null -w "mock systems from outside: HTTP %{http_code} (expect 403)\n" "$URL/mock/crm/customers/C1001" || true
curl -fsS -X POST "$URL/answer" -d From=919800000001 | head -c 200; echo
echo "Deployed: $URL"
echo "Ops panel admin: open $URL/?admin=<ADMIN_TOKEN from .env>"
echo "Phone: point the Vobiz/Twilio answer URL (and hangup/fallback URLs) at $URL/answer (POST)."
